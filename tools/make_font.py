#!/usr/bin/env python3
"""Pack the EF3 font's 256 pointers as low bytes plus packed 2-bit high parts.

All original glyph bytes and all 256 mappings are retained. The original
charset.sed, Thomas Giesel's copyright and EF3-LICENSE.md remain authoritative.
"""
import argparse
from pathlib import Path
import re


def read_font(path):
    text=Path(path).read_text(errors='replace')
    lookup_text=text.split('charset_tab_lo:',1)[1].split('.export charset_tab_hi',1)[0]
    lookup=[int(x) for x in re.findall(r'<ch_(\d+)',lookup_text)]
    labels={}
    data=[]
    for line in text.splitlines():
        label=re.match(r'ch_(\d+):',line)
        if label: labels[int(label[1])]=len(data)
        bits=re.fullmatch(r'[#-]{8}',line.strip())
        if bits: data.append(int(bits[0].replace('#','1').replace('-','0'),2))
    assert len(lookup)==256
    offsets=[labels[n] for n in lookup]
    assert max(offsets)<1024
    return bytes(data),offsets


def glyph(data,offset):
    end=offset+1
    while data[end]: end+=1
    return data[offset:end]  # columns; omit the terminating zero


def rows(values):
    return ['    .byte '+', '.join(f'${x:02x}' for x in values[i:i+16]) for i in range(0,len(values),16)]


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('source',type=Path)
    ap.add_argument('output',type=Path)
    args=ap.parse_args()
    data,offsets=read_font(args.source)
    low=[n&255 for n in offsets]
    high=[sum((offsets[i+j]>>8)<<(j*2) for j in range(4)) for i in range(0,256,4)]
    for i,offset in enumerate(offsets):
        decoded=low[i]+(((high[i//4]>>(2*(i%4)))&3)<<8)
        assert decoded==offset
        assert glyph(data,decoded)==glyph(data,offset)
    out=['; Altered EF3 font pointer layout. Generated by tools/make_font.py.',
         '; Font (c) Thomas Giesel. See EF3-LICENSE.md and charset.sed.',
         '.rodata','.export charset_offset_lo, charset_offset_hi, charset_data',
         'charset_offset_lo:',*rows(low),'charset_offset_hi:',*rows(high),
         'charset_data:',*rows(data),'']
    args.output.write_text('\n'.join(out))
    print(f'Font: {len(data)+320} bytes, 256 mappings verified (was {len(data)+512}).')

if __name__=='__main__': main()
